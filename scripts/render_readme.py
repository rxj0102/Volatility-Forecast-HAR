"""Render the README Key Results block from the files in results/.

    python scripts/render_readme.py          # rewrite the block in README.md
    python scripts/render_readme.py --check  # exit 1 if README.md is out of date
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"

LABELS = {
    "HAR_Pred": "HAR-RV",
    "Lasso_Pred": "Lasso",
    "EN_Pred": "ElasticNet",
    "Stacked_Pred": "Stacked (SLSQP)",
    "EqualWeight_Pred": "Equal-weight ensemble",
    "XGB_Pred": "XGBoost",
    "Regime_Pred": "Regime-switching ensemble",
    "RF_Pred": "Random Forest",
    "GJR_lag1": "GJR-GARCH-t",
    "EGARCH_lag1": "EGARCH-t",
    "GARCH_lag1": "GARCH-t",
    "HAR_W_lag1": "Weekly RV (naive)",
    "HAR_M_lag1": "Monthly RV (naive)",
}


def render() -> str:
    h = json.loads((RES / "headline.json").read_text())
    tm = pd.read_csv(RES / "test_metrics.csv", index_col="Model").sort_values("MSE")
    dm = pd.read_csv(RES / "dm_tests.csv")
    covid = pd.read_csv(RES / "covid_metrics.csv", index_col="Model").sort_values("MSE")

    har = tm.loc["HAR_Pred"]
    ml = tm.loc[["Lasso_Pred", "EN_Pred", "Stacked_Pred", "RF_Pred", "XGB_Pred"]]
    best = ml["MSE"].idxmin()
    dmm = dm.set_index(["Model", "Loss"])
    p_mse = dmm.loc[(best, "MSE"), "p_hac"]
    p_ql = dmm.loc[(best, "QLIKE"), "p_hac"]
    gap = (ml.loc[best, "MSE"] / har["MSE"] - 1) * 100

    o = []
    o.append(
        f"Test window {h['test_start']} to {h['test_end']} ({h['n_test']} days), models trained on "
        f"{h['train_start']} to {h['train_end']} ({h['n_train']} days). Target: next-day 5-day realized volatility."
    )
    o.append("")
    o.append("| Model | Test MSE | QLIKE | R² | DM vs HAR, p (HAC, MSE) |")
    o.append("|---|---|---|---|---|")
    for m, r in tm.iterrows():
        p = "" if m == "HAR_Pred" else f"{dmm.loc[(m, 'MSE'), 'p_hac']:.3f}"
        o.append(f"| {LABELS.get(m, m)} | {r.MSE:.2e} | {r.QLIKE:.4f} | {r.R2:.3f} | {p} |")
    o.append("")
    o.append("| Finding | Evidence |")
    o.append("|---|---|")
    sig = "significant" if min(p_mse, p_ql) <= 0.05 else "not significant"
    lead = "lowest" if tm.index[0] == "HAR_Pred" else "not the lowest"
    o.append(
        f"| HAR-RV has the {lead} test MSE | Best ML model ({LABELS[best]}) has {gap:+.1f}% higher MSE; "
        f"the HAC Diebold-Mariano difference is {sig} (p = {p_mse:.3f} for MSE, {p_ql:.3f} for QLIKE) |"
    )
    w = h["meta_weights"]
    o.append(
        f"| The stacker ignores the tree models | SLSQP weights: Lasso {w['Lasso']:.2f}, ElasticNet {w['EN']:.2f}, "
        f"Random Forest {w['RF']:.2f}, XGBoost {w['XGB']:.2f} |"
    )
    rg, ew = tm.loc["Regime_Pred", "MSE"], tm.loc["EqualWeight_Pred", "MSE"]
    o.append(
        f"| Regime switching does not help | Regime ensemble MSE is {(rg / ew - 1) * 100:+.1f}% vs the equal-weight ensemble |"
    )
    hc, ec = covid.loc["HAR (pre-COVID)", "MSE"], covid.loc["EN (pre-COVID)", "MSE"]
    o.append(
        f"| HAR holds up best in the COVID window | Retrained on pre-2020 data, HAR has the lowest MSE over Feb to Jun 2020; "
        f"ElasticNet is {(ec / hc - 1) * 100:+.1f}% worse, Random Forest {(covid.loc['RF (pre-COVID)', 'MSE'] / hc - 1) * 100:+.0f}% worse |"
    )
    c = h["har_coef"]
    o.append("")
    o.append(
        f"Fitted HAR-RV: RV(t+1) = {c['intercept']:.4f} + {c['beta_d']:.4f} RV_d + {c['beta_w']:.4f} RV_w + {c['beta_m']:.4f} RV_m."
    )
    return "\n".join(o)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    if START not in text or END not in text:
        sys.exit("README.md has no results markers")
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    new = pre + START + "\n" + render() + "\n" + END + post
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md Key Results are out of date. Run: python scripts/render_readme.py")
        print("README.md Key Results match results/")
        return
    readme.write_text(new)
    print("README.md Key Results rendered from results/")


if __name__ == "__main__":
    main()
