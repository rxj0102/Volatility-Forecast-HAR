"""Render the README results from results/metrics.json.

    python scripts/render_readme.py          rewrite the generated blocks
    python scripts/render_readme.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
ML = ["Lasso", "Random forest", "Gradient boosting"]
ORDER = ["No change", "EWMA", "GARCH", "GJR-GARCH", "VIX", "HAR", "SHAR", "HAR-X", "Lasso", "Random forest",
         "Gradient boosting", "HAR-X + boosting"]


def sig(p):
    return p is not None and p < 0.05


def headline(m: dict) -> str:
    hs = m["horizons"]
    wins = {h: [k for k in ML if hs[h]["models"][k]["qlike_vs_har"] < 0 and sig(hs[h]["models"][k]["dm_p_qlike"])]
            for h in hs}
    loses = {h: [k for k in ML if hs[h]["models"][k]["qlike_vs_har"] > 0 and sig(hs[h]["models"][k]["dm_p_qlike"])]
             for h in hs}
    best = {h: hs[h]["best_qlike"] for h in hs}
    beats_gjr = [(h, k) for h in hs for k in ML
                 if hs[h]["ml_vs_gjr_qlike"][k]["t"] < 0 and sig(hs[h]["ml_vs_gjr_qlike"][k]["p"])]
    checks = {
        "GJR-GARCH has the lowest QLIKE at 1 and 5 days": best["1"] in ("GJR-GARCH", "Random forest") and best["5"] == "GJR-GARCH",
        "no ML model significantly beats GJR-GARCH on QLIKE at any horizon": not beats_gjr,
        "random forest beats HAR at 1 and 5 days": "Random forest" in wins["1"] and "Random forest" in wins["5"],
        "no ML model beats HAR at 22 days": not wins["22"],
        "gradient boosting has higher QLIKE than HAR everywhere": all(hs[h]["models"]["Gradient boosting"]["qlike_vs_har"] > 0 for h in hs),
        "lasso beats HAR on MSE and not on QLIKE at 1 and 5 days": all(
            hs[h]["models"]["Lasso"]["dm_t_mse"] < -1.96 and hs[h]["models"]["Lasso"]["qlike_vs_har"] > 0 for h in ("1", "5")),
        "gradient boosting never beats HAR": all("Gradient boosting" not in wins[h] for h in hs),
        "SHAR beats HAR at 5 and 22 days": all(hs[h]["models"]["SHAR"]["dm_t_qlike"] < -1.96 for h in ("5", "22")),
        "SHAR does not beat HAR at 1 day": not sig(hs["1"]["models"]["SHAR"]["dm_p_qlike"]) or hs["1"]["models"]["SHAR"]["dm_t_qlike"] > 0,
        "SHAR closes less than a third of the gap to GJR-GARCH at 5 days":
            hs["5"]["models"]["SHAR"]["qlike_vs_har"] > hs["5"]["models"]["GJR-GARCH"]["qlike_vs_har"] / 3,
        "GJR-GARCH still beats SHAR at 1 and 5 days": all(hs[h]["shar_vs_gjr_qlike"]["t"] > 1.96 for h in ("1", "5")),
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_readme.py. Failed: " + "; ".join(failed))
    one, five = hs["1"]["models"], hs["5"]["models"]
    s = m["sample"]
    return (
        f"**Answer, on {hs['1']['n_forecasts']} out-of-sample days from {s['first_forecast_year']} to "
        f"{s['last_day'][:4]}: sometimes, and it is the wrong comparison.** A random forest has a lower "
        f"QLIKE loss than HAR at 1 and 5 days (Diebold-Mariano t = {one['Random forest']['dm_t_qlike']:.1f} and "
        f"{five['Random forest']['dm_t_qlike']:.1f}) but not at 22 days, and not under squared error at any "
        f"horizon. Gradient boosting has a higher QLIKE loss than HAR at every horizon. The lasso "
        f"beats HAR under squared error at 1 and 5 days and loses to it under QLIKE. The "
        f"model that matters is an old one. GJR-GARCH, a four-parameter model from 1993 in which "
        f"falling prices raise variance more than rising ones, beats HAR at 1 and 5 days "
        f"(t = {one['GJR-GARCH']['dm_t_qlike']:.1f} and {five['GJR-GARCH']['dm_t_qlike']:.1f}). The random "
        f"forest matches it at 1 day and no machine learning model is significantly better than it at "
        f"any horizon. What HAR lacks is the asymmetry, not flexibility. Giving HAR the asymmetry directly, "
        f"by splitting yesterday's squared return by sign as Patton and Sheppard (2015) do, helps at 5 and 22 "
        f"days (t = {five['SHAR']['dm_t_qlike']:.1f} and {hs['22']['models']['SHAR']['dm_t_qlike']:.1f}) but "
        f"closes less than a third of the gap to GJR-GARCH at 5 days, which still beats it at 1 and 5 days "
        f"(t = {hs['1']['shar_vs_gjr_qlike']['t']:.1f} and {hs['5']['shar_vs_gjr_qlike']['t']:.1f}, positive "
        f"favours GJR-GARCH)."
    )


def results(m: dict) -> str:
    s = m["sample"]
    out = [f"Daily data {s['first_day']} to {s['last_day']} ({s['n_days']} days). Every model is refitted each "
           f"January on earlier data only; forecasts start in {s['first_forecast_year']}. QLIKE is shown relative "
           f"to HAR, so negative is better than HAR. t is the Diebold-Mariano statistic against HAR with "
           f"Newey-West errors; beyond about 2 in either direction is significant at 5%."]
    for h, r in m["horizons"].items():
        out += ["", f"**{h} day horizon** ({r['n_forecasts']} forecasts, {r['first']} to {r['last']})", "",
                "| Model | QLIKE vs HAR | t (QLIKE) | MSE vs HAR | t (MSE) | R squared | Forecasts floored |",
                "|---|---|---|---|---|---|---|"]
        har = r["models"]["HAR"]
        for k in ORDER:
            x = r["models"][k]
            if k == "HAR":
                out.append(f"| **HAR** | 0 | | 0 | | {x['r2']:.2f} | {r['floored_share']['HAR']:.1%} |")
                continue
            fl = f"{r['floored_share'][k]:.1%}" if k in r["floored_share"] else "n/a"
            out.append(f"| {k} | {x['qlike_vs_har']:+.3f} | {x['dm_t_qlike']:+.1f} | "
                       f"{x['mse'] / har['mse'] - 1:+.1%} | {x['dm_t_mse']:+.1f} | {x['r2']:.2f} | {fl} |")
    out += ["", "**Machine learning against GJR-GARCH** (QLIKE, Diebold-Mariano t; negative favours the "
            "machine learning model). This comparison was added after the first run showed which model was "
            "the one to beat.", "", "| Model | " + " | ".join(f"{h} day" for h in m["horizons"]) + " |",
            "|---|" + "---|" * len(m["horizons"])]
    for k in ML:
        out.append(f"| {k} | " + " | ".join(f"{m['horizons'][h]['ml_vs_gjr_qlike'][k]['t']:+.1f}"
                                            for h in m["horizons"]) + " |")
    five = m["horizons"]["5"]["periods"]
    labs = list(five)
    out += ["", "**By period, 5 day horizon**: QLIKE relative to HAR", "", "| Model | " + " | ".join(labs) + " |",
            "|---|" + "---|" * len(labs)]
    for k in ("GJR-GARCH", "HAR-X", "Random forest", "Gradient boosting"):
        out.append(f"| {k} | " + " | ".join(f"{five[p][k]:+.3f}" for p in labs) + " |")
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
